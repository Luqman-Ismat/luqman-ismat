/* Scope the demo apps' stylesheets so they can render directly inside site
   pages: every selector is prefixed with .demo-scope, document-level rules
   (:root, html, body) land on the scope itself, and the apps' own
   [data-theme=light] overrides follow the site's light/dark class. Their
   hard-coded brand teal is routed through var(--accent) so the site (or a
   visitor re-branding the demo) controls it. */
import postcss from "postcss";
import { readFile, writeFile } from "node:fs/promises";

const SCOPE = ".demo-scope";
const DOC = /^(?::root|html|body)(?=$|[\s>+~.:[])/;

function scopeSelector(raw) {
  let sel = raw.trim();
  let theme = null;
  const themed = sel.match(/^(?::root|html|body)?\[data-theme=["']?(dark|light)["']?\]/);
  if (themed) {
    theme = themed[1];
    sel = sel.slice(themed[0].length).trim();
  }
  sel = sel.replace(DOC, "").trim();
  sel = sel.replace(/^body(?=$|[\s>+~.:[])/, "").trim();
  const prefix = theme === "dark" ? `html.dark ${SCOPE}` : theme === "light" ? `html:not(.dark) ${SCOPE}` : SCOPE;
  if (!sel) return prefix;
  // pseudo-classes that belonged to the document element now apply to the scope
  if (/^:(?!:)/.test(sel)) return `${prefix}${sel}`;
  return `${prefix} ${sel}`;
}

const teal = /rgba\(\s*46\s*,\s*196\s*,\s*182\s*,\s*([\d.]+)\s*\)/g;
/* The apps were drawn dark-first: white-at-alpha means "a foreground tint" and
   these near-blacks mean "a surface". Expressing both through site tokens
   lets the same rules work on light and dark grounds. */
const whiteAlpha = /rgba\(\s*255\s*,\s*255\s*,\s*255\s*,\s*([\d.]+)\s*\)/g;
const surfaces = /#(?:08090a|0a0b0c|061418|111316|0b0d0f|0c1013|111214|141517|141718|16171a|191b1e)\b/gi;
function recolour(value, name) {
  let v = value
    .replace(whiteAlpha, (_, a) => `hsl(var(--foreground) / ${a})`)
    .replace(/#ffffff([0-9a-f]{2})\b/gi, (_, a) => `hsl(var(--foreground) / ${(parseInt(a, 16) / 255).toFixed(3)})`)
    .replace(surfaces, "hsl(var(--card))")
    .replace(/#32d7c8\b/gi, "color-mix(in oklab, var(--accent) 80%, white)");
  if (name === "project") v = v.replace(/#fff(?:fff)?\b/gi, "hsl(var(--foreground))");
  return v
    .replace(/#2ec4b6([0-9a-f]{2})\b/gi, (_, a) => `color-mix(in oklab, var(--accent) ${Math.round((parseInt(a, 16) / 255) * 100)}%, transparent)`)
    .replace(/#2ec4b6\b/gi, "var(--accent)")
    .replace(/#1f8d84\b/gi, "var(--accent-dim)")
    .replace(/#0d8a80([0-9a-f]{2})\b/gi, (_, a) => `color-mix(in oklab, var(--accent) ${Math.round((parseInt(a, 16) / 255) * 100)}%, transparent)`)
    .replace(/#0d8a80\b/gi, "var(--accent)")
    .replace(/rgba\(\s*13\s*,\s*138\s*,\s*128\s*,\s*([\d.]+)\s*\)/g, (_, a) => `color-mix(in oklab, var(--accent) ${Math.round(parseFloat(a) * 100)}%, transparent)`)
    .replace(teal, (_, a) => `color-mix(in oklab, var(--accent) ${Math.round(parseFloat(a) * 100)}%, transparent)`);
}

const scope = (name) => ({
  postcssPlugin: "scope-demo",
  Once(root) {
    root.walkRules((rule) => {
      const parent = rule.parent;
      if (parent?.type === "atrule" && /keyframes$/i.test(parent.name)) return;
      rule.selectors = [...new Set(rule.selectors.map(scopeSelector))];
    });
    root.walkDecls((decl) => {
      // the apps' own --background/--foreground are colours, the site's are
      // HSL channel lists; rename the apps' so the site tokens pass through
      if (decl.prop === "--background" || decl.prop === "--foreground") decl.prop = `--app${decl.prop.slice(1)}`;
      decl.value = recolour(decl.value, name).replace(/var\(--(background|foreground)\)/g, "var(--app-$1)");
    });
    root.walkAtRules("font-face", (at) => at.remove());
  },
});
scope.postcss = true;

for (const name of ["project", "inspection"]) {
  const from = `public/examples/${name}/style.css`;
  const to = `public/examples/${name}/scoped.css`;
  const css = await readFile(from, "utf8");
  const out = await postcss([scope(name)]).process(css, { from, to });
  await writeFile(to, `/* Generated by scripts/scope-demo-css.mjs from style.css. Do not edit. */\n${out.css}`);
  console.log(`scoped ${from} -> ${to} (${(out.css.length / 1024).toFixed(0)} KB)`);
}
